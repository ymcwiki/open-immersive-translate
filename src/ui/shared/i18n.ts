const tables: Record<UiLocale, Record<I18nKey, string>> = {
  "zh-CN": zhCN,
  "zh-TW": zhTW,
  ja,
  en,
};

let localeOverride: UiLocaleSetting = "auto";

export function normalizeUiLocale(value: string | undefined): UiLocale {
  if (!value) return "zh-CN";
  const locale = value?.replace("_", "-").toLowerCase();
  if (locale?.startsWith("zh-tw") || locale?.startsWith("zh-hk"))
    return "zh-TW";
  if (locale?.startsWith("zh")) return "zh-CN";
  if (locale?.startsWith("ja")) return "ja";
  return "en";
}

export function setUiLocaleOverride(locale: UiLocaleSetting | undefined): void {
  localeOverride = locale ?? "auto";
}

export function currentUiLocale(): UiLocale {
  if (localeOverride !== "auto") return localeOverride;
  const chromeLanguage = (
    globalThis as unknown as {
      chrome?: { i18n?: { getUILanguage?(): string } };
    }
  ).chrome?.i18n?.getUILanguage?.();
  return normalizeUiLocale(chromeLanguage);
}

/** Resolve a UI string and replace named placeholders. */
export function t(
  key: I18nKey,
  values: Record<string, string | number> = {},
  locale: UiLocale = currentUiLocale(),
): string {
  return Object.entries(values).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    tables[locale][key],
  );
}

export function serviceName(id: string): string {
  const key = `service.${id}` as I18nKey;
  return key in zhCN ? t(key) : id;
}

export function languageName(code: string): string {
  const key = `lang.${code}` as I18nKey;
  return key in zhCN ? t(key) : code;
}
